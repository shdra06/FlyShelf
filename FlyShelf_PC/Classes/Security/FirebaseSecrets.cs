        /// <summary>Firebase Web API Key (decoded at runtime from obfuscated bytes).</summary>
        public static string ApiKey => Deobfuscate(_apiKeyData);

        /// <summary>Firebase Realtime Database URL (decoded at runtime from obfuscated bytes).</summary>
        public static string DatabaseUrl => Deobfuscate(_dbUrlData);

        /// <summary>
        /// XOR-decodes an obfuscated byte array back to the original string.
        /// </summary>
        private static string Deobfuscate(byte[] data)
        {
            var result = new byte[data.Length];
            for (int i = 0; i < data.Length; i++)
            {
                result[i] = (byte)(data[i] ^ _xorKey[i % _xorKey.Length]);
            }
            return System.Text.Encoding.UTF8.GetString(result);
        }

    }
