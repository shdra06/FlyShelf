    /// <summary>
    /// Holds the Firebase API Key and Database URL.
    /// This file is Git-ignored to prevent exposing actual credentials in the public repository.
    /// 
    /// SECURITY: Keys are XOR-obfuscated so they do not appear as plaintext strings
    /// in the compiled binary. This prevents casual extraction via `strings`, decompilers,
    /// or automated secret scanners. The obfuscation key is derived from the app's
    /// identity, making byte patterns non-obvious.
    ///
    /// NOTE: The Firebase Web API Key is a PUBLIC CLIENT KEY, not a server secret.
    /// Access to Firebase resources is controlled by Firebase Security Rules.
    /// See: https://firebase.google.com/docs/projects/api-keys
